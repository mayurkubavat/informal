//! Single-source-of-truth Reference Manual generator (`informal docgen`).
//!
//! Introspects live Rust registries to emit zero-drift Markdown manuals,
//! a machine-readable catalog (`docs/reference/index.json`), and `llms.txt`:
//!
//! 1. `clap::Command` (`Cli::command()`) -> `docs/reference/cli.md`
//! 2. `informal_fpv::compat::help::all_docs()` -> `docs/reference/tcl-commands.md`
//!    and `docs/reference/jg-vcf-crosswalk.md`
//! 3. `informal_mcp::{tools, prompts, spec}` -> `docs/reference/mcp-tools.md`
//!    and `docs/reference/spec-schema.md`
//! 4. Unified index -> `docs/reference/index.json` and `llms.txt`
//!
//! Run `informal docgen` to regenerate; `informal docgen --check` fails with a
//! non-zero exit status if any generated file on disk has drifted from code.

use anyhow::{bail, Context};
use clap::Command;
use informal_fpv::compat::help::{self, Category, CmdDoc, DocFlavor};
use informal_mcp::tools::Tool;
use informal_mcp::{prompts, spec, tools, Mode};
use serde_json::{json, Value};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const HEADER: &str = "<!-- AUTO-GENERATED by `informal docgen`. Do not edit by hand; run `informal docgen` to regenerate. -->\n\n";

pub fn run(
    cli_cmd: Command,
    out_dir: &Path,
    llms_out: Option<&Path>,
    check: bool,
) -> anyhow::Result<()> {
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    files.insert(out_dir.join("cli.md"), render_cli(&cli_cmd));
    files.insert(out_dir.join("tcl-commands.md"), render_tcl_commands());
    files.insert(out_dir.join("jg-vcf-crosswalk.md"), render_crosswalk());
    files.insert(out_dir.join("mcp-tools.md"), render_mcp_tools());
    files.insert(out_dir.join("spec-schema.md"), render_spec_schema());
    files.insert(out_dir.join("index.json"), render_index_json(&cli_cmd));
    if let Some(llms) = llms_out {
        files.insert(llms.to_path_buf(), render_llms_txt());
    }

    if check {
        let mut drifted = Vec::new();
        for (path, expected) in &files {
            match std::fs::read_to_string(path) {
                Ok(actual) if actual == *expected => {}
                Ok(_) => drifted.push(format!("{} (out of date)", path.display())),
                Err(_) => drifted.push(format!("{} (missing)", path.display())),
            }
        }
        if !drifted.is_empty() {
            bail!(
                "generated documentation is out of date:\n  - {}\nRun `informal docgen` to regenerate.",
                drifted.join("\n  - ")
            );
        }
        println!("docgen: {} generated files are up to date.", files.len());
        return Ok(());
    }

    for (path, content) in &files {
        if let Some(parent) = path.parent() {
            if !parent.as_os_str().is_empty() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("creating {}", parent.display()))?;
            }
        }
        std::fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
    }
    println!(
        "docgen: wrote {} files under {}.",
        files.len(),
        out_dir.display()
    );
    Ok(())
}

fn md_escape(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn format_arg_spec(arg: &clap::Arg) -> String {
    let mut parts = Vec::new();
    if let Some(short) = arg.get_short() {
        parts.push(format!("-{short}"));
    }
    if let Some(long) = arg.get_long() {
        parts.push(format!("--{long}"));
    }
    let val_names = arg
        .get_value_names()
        .map(|vs| {
            vs.iter()
                .map(|v| format!("<{v}>"))
                .collect::<Vec<_>>()
                .join(" ")
        })
        .unwrap_or_default();
    if parts.is_empty() {
        let id = arg.get_id().as_str();
        if !val_names.is_empty() {
            val_names
        } else {
            format!("<{id}>")
        }
    } else if arg.get_action().takes_values() {
        let vn = if val_names.is_empty() {
            format!("<{}>", arg.get_id().as_str().to_uppercase())
        } else {
            val_names
        };
        format!("{} {}", parts.join(", "), vn)
    } else {
        parts.join(", ")
    }
}

fn render_cli(root: &Command) -> String {
    let mut out = String::from(HEADER);
    out.push_str("# CLI Reference Manual (`informal`)\n\n");
    out.push_str(
        "Complete command-line interface reference generated directly from `crates/informal-cli/src/main.rs`.\n\n",
    );
    out.push_str("## Synopsis\n\n```sh\ninformal [GLOBAL OPTIONS] <COMMAND> [ARGS]\n```\n\n");

    out.push_str("## Global Options\n\n");
    out.push_str("| Option | Description |\n| --- | --- |\n");
    for arg in root.get_arguments() {
        if arg.is_hide_set() {
            continue;
        }
        let spec = format_arg_spec(arg);
        let help = arg.get_help().map(|h| h.to_string()).unwrap_or_default();
        out.push_str(&format!(
            "| `{}` | {} |\n",
            md_escape(&spec),
            md_escape(&help)
        ));
    }
    out.push_str("| `-h, --help` | Print help information |\n");
    out.push_str("| `-V, --version` | Print version information |\n\n");

    out.push_str("## Subcommands Summary\n\n");
    out.push_str("| Command | Purpose |\n| --- | --- |\n");
    for sub in root.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        let name = sub.get_name();
        let about = sub.get_about().map(|a| a.to_string()).unwrap_or_default();
        out.push_str(&format!(
            "| [`informal {name}`](#informal-{name}) | {} |\n",
            md_escape(&about)
        ));
    }
    out.push('\n');

    out.push_str("## Exit Codes\n\n");
    out.push_str("| Context | Exit code | Meaning |\n| --- | --- | --- |\n");
    out.push_str("| `informal check` | `10` | **UNSAFE** — counterexample found and replayed |\n");
    out.push_str("| `informal check` | `20` | **SAFE** — unbounded proof verified |\n");
    out.push_str("| `informal check` | `0` | **UNKNOWN** — timeout or inconclusive |\n");
    out.push_str("| `informal shell --check` | `0` | Script clean (only honoured or ignored vendor options) |\n");
    out.push_str("| `informal shell --check` | `1` | Script has rejected options, unknown commands, or Tcl errors |\n");
    out.push_str("| Any command | `3` | Memory budget exceeded (`--mem-gb` or cgroup limit) |\n");
    out.push_str("| Any command | `1` / `2` | Runtime error or CLI usage error |\n\n");

    out.push_str("## Environment Variables\n\n");
    out.push_str("| Variable | Effect |\n| --- | --- |\n");
    out.push_str("| `INFORMAL_ISOLATE` | Run each in-house engine in an isolated child process (equivalent to `--isolate`) |\n");
    out.push_str("| `INFORMAL_WAVE_VIEWER` | Waveform viewer spawned by Tcl `visualize` (e.g., `surfer`, `gtkwave`) |\n");
    out.push_str("| `INFORMAL_AI_SOCKET` | Override desktop app Unix socket path, or `off` to disable AI socket |\n");
    out.push_str("| `INFORMAL_AI_MODE` | Desktop app MCP permission mode (`read-only`, `propose`, `auto`) |\n");
    out.push_str(
        "| `INFORMAL_ROOT` | Default workspace root passed by the Antigravity MCP launcher |\n",
    );
    out.push_str("| `INFORMAL_TOOLS_DIR` | Build/runtime directory for external solvers (`cadical`, `bitwuzla`) |\n");
    out.push_str("| `INFORMAL_CADICAL_DIR` | Explicit CaDiCaL build directory override |\n");
    out.push_str("| `INFORMAL_BITWUZLA_DIR` | Explicit Bitwuzla install directory override |\n\n");

    out.push_str("## Subcommand Details\n\n");
    for sub in root.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        let name = sub.get_name();
        out.push_str(&format!("### `informal {name}`\n\n"));
        if let Some(about) = sub.get_about() {
            out.push_str(&format!("{about}\n\n"));
        }
        let mut usage = format!("informal {name}");
        for arg in sub.get_arguments() {
            if arg.is_hide_set() || arg.is_global_set() {
                continue;
            }
            if arg.is_positional() {
                let id = arg.get_id().as_str();
                if arg.is_required_set() {
                    usage.push_str(&format!(" <{id}>"));
                } else {
                    usage.push_str(&format!(" [{id}]"));
                }
            }
        }
        let has_flags = sub
            .get_arguments()
            .any(|a| !a.is_hide_set() && !a.is_global_set() && !a.is_positional());
        if has_flags {
            usage.push_str(" [OPTIONS]");
        }
        out.push_str(&format!("```sh\n{usage}\n```\n\n"));

        let args: Vec<&clap::Arg> = sub
            .get_arguments()
            .filter(|a| !a.is_hide_set() && !a.is_global_set())
            .collect();
        if !args.is_empty() {
            out.push_str("| Argument / Option | Default | Description |\n| --- | --- | --- |\n");
            for arg in args {
                let spec = format_arg_spec(arg);
                let defaults: Vec<String> = arg
                    .get_default_values()
                    .iter()
                    .map(|v| format!("`{}`", v.to_string_lossy()))
                    .collect();
                let def_str = if defaults.is_empty() {
                    "—".to_string()
                } else {
                    defaults.join(", ")
                };
                let help = arg.get_help().map(|h| h.to_string()).unwrap_or_default();
                out.push_str(&format!(
                    "| `{}` | {} | {} |\n",
                    md_escape(&spec),
                    md_escape(&def_str),
                    md_escape(&help)
                ));
            }
            out.push('\n');
        }
    }
    out
}

fn render_tcl_commands() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Tcl Command Reference Manual (`informal shell`)\n\n");
    out.push_str(
        "Complete reference for all commands available in `informal shell`, generated directly from `crates/informal-compat/src/compat/help.rs`.\n\n",
    );
    out.push_str(
        "> **Interactive help:** Inside `informal shell`, run `help`, `help -apps`, `help -all`, or `help <command>` to view this exact documentation.\n\n",
    );
    out.push_str("## Flavors\n\n");
    out.push_str("- **`common`**: Available in every flavor (`::informal::<cmd>`, `::jg::<cmd>`, `::vcf::<cmd>`).\n");
    out.push_str("- **`jg`**: JasperGold-style flavor (`informal shell --flavor jg`, auto-detected by default).\n");
    out.push_str("- **`vcf`**: VC Formal-style flavor (`informal shell --flavor vcf`, auto-detected when `read_file`/`create_clock`/`fvassert`/`check_fv` appear).\n\n");

    let docs = help::all_docs();
    out.push_str("## Contents by Category\n\n");
    for &cat in Category::ALL {
        let count = docs.iter().filter(|d| d.category == cat).count();
        out.push_str(&format!("- **{}** ({count} commands)\n", cat.title()));
    }
    out.push('\n');

    for &cat in Category::ALL {
        let items: Vec<&CmdDoc> = docs.iter().filter(|d| d.category == cat).collect();
        if items.is_empty() {
            continue;
        }
        out.push_str(&format!("## {}\n\n", cat.title()));
        for d in items {
            out.push_str(&format!("### `{}` (`{}`)\n\n", d.name, d.flavor.label()));
            out.push_str(&format!("{}\n\n", d.summary));
            out.push_str(&format!("```tcl\n{}\n```\n\n", d.usage));
            if !d.options.is_empty() {
                out.push_str("| Option | Description |\n| --- | --- |\n");
                for o in d.options {
                    out.push_str(&format!(
                        "| `{}` | {} |\n",
                        md_escape(o.flag),
                        md_escape(o.desc)
                    ));
                }
                out.push('\n');
            }
            if !d.ignored_options.is_empty() {
                let list: Vec<String> =
                    d.ignored_options.iter().map(|o| format!("`{o}`")).collect();
                out.push_str(&format!(
                    "**Accepted & ignored vendor options:** {}\n\n",
                    list.join(", ")
                ));
            }
            if let Some(eq) = d.equivalent {
                out.push_str(&format!("**Cross-flavor equivalent:** {eq}\n\n"));
            }
            if !d.notes.is_empty() {
                out.push_str(&format!("**Notes:** {}\n\n", d.notes));
            }
            if !d.example.is_empty() {
                out.push_str(&format!("```tcl\n{}\n```\n\n", d.example));
            }
        }
    }
    out
}

