fn schema_type_label(prop: &Value) -> String {
    if let Some(en) = prop.get("enum").and_then(|v| v.as_array()) {
        let vals: Vec<String> = en
            .iter()
            .filter_map(|v| v.as_str())
            .map(|s| format!("`{s}`"))
            .collect();
        return format!("enum ({})", vals.join(" \\| "));
    }
    match prop.get("type").and_then(|v| v.as_str()) {
        Some("array") => {
            let inner = prop
                .get("items")
                .and_then(|i| i.get("type"))
                .and_then(|t| t.as_str())
                .unwrap_or("any");
            format!("array\\<{inner}\\>")
        }
        Some(t) => t.to_string(),
        None => "any".to_string(),
    }
}

fn render_tool_section(out: &mut String, tool: &Tool, is_gui: bool) {
    let mode_tag = if is_gui {
        "Desktop window (`--connect` / InFormal.app), all modes"
    } else if tool.changes {
        "`propose` (waits for approval) / `auto` (applied immediately); hidden in `read-only`"
    } else {
        "All modes (`read-only`, `propose`, `auto`)"
    };
    let out_schema = tool
        .output
        .pointer("/properties/schema/const")
        .and_then(|v| v.as_str())
        .unwrap_or("object");

    out.push_str(&format!("### `{}`\n\n", tool.name));
    out.push_str(&format!("**{}** — {}\n\n", tool.title, tool.description));
    out.push_str(&format!(
        "- **Availability:** {mode_tag}\n- **Mutates session:** {}\n- **Reply schema:** `{out_schema}`\n\n",
        if tool.changes { "yes (by mode)" } else { "no" }
    ));

    let required: Vec<&str> = tool
        .input
        .get("required")
        .and_then(|v| v.as_array())
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();
    if let Some(props) = tool.input.get("properties").and_then(|v| v.as_object()) {
        if !props.is_empty() {
            out.push_str(
                "| Parameter | Type | Required | Description |\n| --- | --- | --- | --- |\n",
            );
            for (k, v) in props {
                let req = if required.contains(&k.as_str()) {
                    "yes"
                } else {
                    "no"
                };
                let desc = v.get("description").and_then(|d| d.as_str()).unwrap_or("");
                out.push_str(&format!(
                    "| `{k}` | {} | {req} | {} |\n",
                    schema_type_label(v),
                    md_escape(desc)
                ));
            }
            out.push('\n');
        }
    }
}

fn render_mcp_tools() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# MCP Tools & Prompts Reference (`informal mcp`)\n\n");
    out.push_str(
        "Complete JSON-RPC Model Context Protocol reference generated directly from `crates/informal-mcp/src/{tools,prompts}.rs`.\n\n",
    );

    let core = tools::for_mode(Mode::Auto, false);
    let all = tools::for_mode(Mode::Auto, true);
    let gui_tools: Vec<&Tool> = all
        .iter()
        .filter(|t| !core.iter().any(|c| c.name == t.name))
        .collect();

    let prompt_count = prompts::list()
        .get("prompts")
        .and_then(|v| v.as_array())
        .map_or(0, Vec::len);
    out.push_str(&format!(
        "- **Core session tools:** {}\n- **Desktop window tools (`gui_*`):** {}\n- **Server-hosted MCP prompts:** {}\n\n",
        core.len(),
        gui_tools.len(),
        prompt_count
    ));

    out.push_str("## Error Contract (`informal.error/1`)\n\n");
    out.push_str(
        "Every tool error returns structured JSON (`isError: true`) with actionable Poka-Yoke recovery fields:\n\n",
    );
    out.push_str("```json\n{\n  \"schema\": \"informal.error/1\",\n  \"code\": \"not_found\",\n  \"message\": \"no property named a_mx\",\n  \"hint\": \"Did you mean `a_max`? Run `property_list` to inspect active properties.\",\n  \"suggested_tool\": \"property_list\",\n  \"candidates\": [\"a_max\"]\n}\n```\n\n");

    out.push_str("## MCP Prompts (`prompts/list`, `prompts/get`)\n\n");
    out.push_str(
        "Server-hosted playbooks dynamically hydrated with the active session's top module, port boundary, clocks/reset, and failing/undetermined properties:\n\n",
    );
    out.push_str("| Prompt | Arguments | Description |\n| --- | --- | --- |\n");
    let plist = prompts::list();
    if let Some(items) = plist.get("prompts").and_then(|v| v.as_array()) {
        for p in items {
            let name = p["name"].as_str().unwrap_or("");
            let desc = p["description"].as_str().unwrap_or("");
            let args = p["arguments"]
                .as_array()
                .map(|arr| {
                    arr.iter()
                        .map(|a| {
                            let an = a["name"].as_str().unwrap_or("");
                            if a["required"].as_bool().unwrap_or(false) {
                                format!("`{an}` (req)")
                            } else {
                                format!("`{an}`")
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_else(|| "—".to_string());
            out.push_str(&format!("| `{name}` | {args} | {} |\n", md_escape(desc)));
        }
    }
    out.push('\n');

    out.push_str("## Core Session Tools\n\n");
    for t in &core {
        render_tool_section(&mut out, t, false);
    }

    out.push_str("## Desktop Window Tools (`gui_*`)\n\n");
    out.push_str(
        "Offered when connected to a running `InFormal.app` session (`informal mcp --connect`). Window tools drive visualization without mutating the formal model.\n\n",
    );
    for t in gui_tools {
        render_tool_section(&mut out, t, true);
    }
    out
}

