fn render_index_json(root: &Command) -> String {
    let cli_cmds: Vec<Value> = root
        .get_subcommands()
        .filter(|s| !s.is_hide_set())
        .map(|s| {
            let flags: Vec<String> = s
                .get_arguments()
                .filter(|a| !a.is_hide_set() && !a.is_global_set())
                .map(format_arg_spec)
                .collect();
            json!({
                "name": s.get_name(),
                "about": s.get_about().map(|a| a.to_string()).unwrap_or_default(),
                "args": flags,
            })
        })
        .collect();

    let core = tools::for_mode(Mode::Auto, false);
    let all = tools::for_mode(Mode::Auto, true);
    let mcp_tools: Vec<Value> = all
        .iter()
        .map(|t| {
            let is_gui = !core.iter().any(|c| c.name == t.name);
            json!({
                "name": t.name,
                "title": t.title,
                "description": t.description,
                "changes": t.changes,
                "gui_only": is_gui,
                "reply_schema": t.output.pointer("/properties/schema/const").and_then(|v| v.as_str()).unwrap_or("object"),
            })
        })
        .collect();

    let index = json!({
        "schema": "informal.docs_index/1",
        "version": env!("CARGO_PKG_VERSION"),
        "cli_subcommands": cli_cmds,
        "tcl_commands": help::to_json(),
        "mcp_tools": mcp_tools,
        "mcp_prompts": prompts::list()["prompts"],
        "spec_schema": spec::SPEC_SCHEMA,
    });
    serde_json::to_string_pretty(&index).expect("index json serializes") + "\n"
}

